"""Compile the existing bit-exact integer transform plus a batched tile renderer.
Requires clang with wasm32 support and wasm-ld (Homebrew lld). The generated
asset is bundled with the app; no compiler or download is needed at runtime.
"""
from pathlib import Path
import re, subprocess, base64, shutil, os
root = Path(__file__).resolve().parents[1]
folder = root / 'Vendor/noVNC-ARD/ard/decoders'
s = (folder / 'mvs-idct.js').read_text()
s = re.sub(r'const (\w+) = (\d+);', r'static const int \1 = \2;', s)
s = s.replace('===', '==')
s = s.replace('const _ws = new Int32Array(64);', 'static int _ws[64];')
s = s.replace('function rangeLimit(v)', 'static int rangeLimit(int v)')
s = s.replace('export function idctFlat(dc)', 'static int idctFlat(int dc)')
s = s.replace('export function idct8x8(block, output)', 'static void idct8x8(int *block, unsigned char *output)')
s = s.replace('const ws = _ws;', 'int *ws = _ws;')
s = re.sub(r'\b(?:const|let) (\w+) =', r'int \1 =', s)
# The zigzag mapping is copied from the same checked-in protocol tables.
tables = (folder / 'mvs-tables.js').read_text()
zigzag = re.search(r'MVS_ZIGZAG = new Uint8Array\(\[([\s\S]*?)\]\)', tables).group(1)
render = (folder / 'wasm/mvs-render.c').read_text()
huffman = (folder / 'mvs-huffman.js').read_text()
entropy_tables = ''
for jsname, cname in [('AC_LUMINANCE_BITS', 'ac_luminance_bits'), ('AC_LUMINANCE_VALUES', 'ac_luminance_values')]:
    values = re.search(jsname + r' = new Uint8Array\(\[([\s\S]*?)\]\)', huffman).group(1)
    entropy_tables += 'static const unsigned char ' + cname + '[] = {' + values + '};\n'
source = s + '\nstatic const unsigned char zigzag[64] = {' + zigzag + '};\n' + render + '\n' + entropy_tables + (folder / 'wasm/mvs-entropy.c').read_text()
build = root / 'Build/MVS'; build.mkdir(parents=True, exist_ok=True)
(build / 'mvs.c').write_text(source)
clang = os.environ.get('CLANG', '/usr/bin/clang')
linker = shutil.which('wasm-ld') or '/opt/homebrew/opt/lld/bin/wasm-ld'
subprocess.run([clang, '--target=wasm32', '-O3', '-fwrapv', '-fno-builtin', '-nostdlib',
 '-fuse-ld=' + linker, '-Wl,--no-entry', '-Wl,--export=render', '-Wl,--export=buffers',
 '-Wl,--export=entropy_buffers', '-Wl,--export=entropy_full', '-Wl,--export=entropy_partial',
 '-Wl,--export=entropy_position', '-Wl,--export-memory', '-Wl,--initial-memory=8585216', '-Wl,--max-memory=8585216',
 str(build / 'mvs.c'), '-o', str(build / 'mvs.wasm')], check=True)
encoded = base64.b64encode((build / 'mvs.wasm').read_bytes()).decode()
(folder / 'mvs-wasm-data.js').write_text('// Generated by Tools/build-mvs-wasm.py; do not edit.\nexport const mvsWasmBase64 = "' + encoded + '";\n')
print('Compiled MVS tile renderer:', (build / 'mvs.wasm').stat().st_size, 'bytes')
